// vulkan-1.dll shim: presents a 1.2 driver as Vulkan 1.3 to vkd3d-proton.
//
// Interception model
// ------------------
// This DLL is named vulkan-1.dll and sits next to the application, so every
// vulkan-1 export lands here first. The real loader is loaded by absolute path
// (System32) and reached with GetProcAddress.
//
// Handles are never wrapped: VkInstance, VkPhysicalDevice, VkDevice and
// VkCommandBuffer pass through unchanged, and our state is keyed by handle
// value. Wrapping would mean reimplementing the loader's dispatch for every
// call, and the driver only accepts its own handles anyway.
//
// Exports come in two kinds:
//   * forwarded   - the real loader's same-named export (generated by
//                   tools/gen_exports.py, which skips the intercepted names)
//   * synthesised - implemented in this DLL on 1.0/1.1/1.2 entry points
#pragma once

#include <windows.h>

#include <vulkan/vulkan.h>

#include <cstdint>
